//! The renderers: golden output for the canonical example, the determinism
//! guarantee (same plan, direction and schedule in, byte-identical file out
//! — including across authoring order), and the self-containment of the
//! HTML. The HTML graph draws with the vendored cytoscape + ELK bundles, so
//! its goldens pin the data block Rust prints (the JSON the glue reads),
//! the layout config, the legend and the file structure — not coordinates,
//! which are the library's now; its critical-path marking is read off the
//! schedule artifact, never recomputed; the glue's interaction wording is
//! pinned as strings. The vendored bundles are pinned verbatim. The gantt's
//! goldens come from the schedule artifact (the golden dates are the
//! scheduler test's, generated by the binary, never hand-computed); its CLI
//! cases run the real binary over tempdirs. The HTML gantt's cases mirror
//! the gantt's: records off the artifact (the dhtmlx data block is the
//! golden surface), the same opt-in gate at the CLI.

use std::process::Command;

use planning_dsl::render::Direction;
use planning_dsl::{Plan, Schedule, load, render, schedule};
use serde_json::Value;

macro_rules! fixture {
    ($name:literal) => {
        include_str!(concat!("fixtures/", $name))
    };
}

const PLAN: &str = fixture!("plan.yaml");

/// The graph's data block, extracted from the artifact and parsed: the
/// golden surface Rust owns — the structure the init glue draws and the
/// card reads.
fn data_block(html: &str) -> Value {
    const OPEN: &str = "<script type=\"application/json\" id=\"graph-data\">";
    let start = html.find(OPEN).expect("the data block is in the shell") + OPEN.len();
    let end = start + html[start..].find("</script>").expect("the block closes");
    serde_json::from_str(&html[start..end]).expect("the data block parses as JSON")
}

