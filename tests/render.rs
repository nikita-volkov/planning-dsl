    let html = render::html(&plan, Direction::Tb, Some(&artifact));
    let task_of = |html: &str, name: &str| -> Value {
        data_block(html)["tasks"]
            .as_array()
            .expect("tasks")
            .iter()
            .find(|t| t["name"] == name)
            .expect("task")
            .clone()
    };
    let services = task_of(&html, "implement-services");
    assert_eq!(
        services["description"],
        "stand up the services the architecture RFC fixes"
    );
