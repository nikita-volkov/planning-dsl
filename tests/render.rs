// The critical path: the html consumes the schedule artifact's chain —
// nodes named in it wear `crit`, edges that are consecutive pairs of it
// wear `crit` — and never recomputes one. The canonical fixture schedules
// to a two-task chain, so a crit edge exists.

fn scheduled_plan() -> (Plan, Schedule) {
    let plan = load(PLAN).expect("parses");
    let artifact = schedule(&plan).expect("schedules");
    (plan, artifact)
}

#[test]
fn the_schedule_chain_marks_crit_nodes_and_consecutive_edges() {
    // The fixture's chain spans exactly two tasks — plan-out-the-tasks →
    // implement-services: design-architecture is done (the scheduler
    // leaves it off the chain) and implement-tests ends earlier (off it
    // too). Only the chain's consecutive pair is a crit edge.
    let (plan, artifact) = scheduled_plan();
    let chain: Vec<&str> = artifact.critical_path.iter().map(String::as_str).collect();
    assert_eq!(chain, ["plan-out-the-tasks", "implement-services"]);
    let html = render::html(&plan, Direction::Tb, Some(&artifact));
    let block = data_block(&html);
    let crit_of = |name: &str| -> bool {
        block["tasks"]
            .as_array()
            .expect("tasks")
            .iter()
            .find(|t| t["name"] == name)
            .expect("task")["crit"]
            == true
    };
    assert!(crit_of("plan-out-the-tasks"), "{html}");
    assert!(crit_of("implement-services"), "{html}");
    assert!(!crit_of("implement-tests"), "{html}");
    assert!(!crit_of("design-architecture"), "{html}");
    // The edge wears crit exactly when it is a consecutive pair.
    let edge_crit = |from: &str, to: &str| -> bool {
        block["edges"]
            .as_array()
            .expect("edges")
            .iter()
            .find(|e| e["from"] == from && e["to"] == to)
            .expect("edge")["crit"]
            == true
    };
    assert!(edge_crit("plan-out-the-tasks", "implement-services"));
    assert!(!edge_crit("plan-out-the-tasks", "implement-tests"));
    assert!(!edge_crit("design-architecture", "plan-out-the-tasks"));
    // Persistent colors, not hover-only; in the dim state the backbone
    // holds 0.4 where the rest drops to 0.15, and the hot rules still
    // out-specify the crit ones.
    assert!(html.contains("selector: 'node.crit'"), "{html}");
    assert!(html.contains("'border-color': '#b91c1c'"), "{html}");
    assert!(html.contains("selector: 'edge.crit'"), "{html}");
    assert!(html.contains("selector: '.dim.crit'"), "{html}");
    assert!(html.contains("opacity: 0.4"), "{html}");
}

