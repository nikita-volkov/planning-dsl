#[test]
fn the_gantt_html_is_a_self_contained_file_with_no_remote_reference() {
    // One file, two inline scripts (the vendored bundle, the data+glue), no
    // external resource of any kind. The vendored stylesheet @font-faces
    // Inter from fonts.gstatic.com — stripped at render time, so the host
    // appears nowhere in the output and an offline open falls back to the
    // system font. The URL counts are the bundle's own inert strings (docs
    // links, the w3.org svg namespace, an export endpoint the readonly
    // config never touches) — none fetched; re-vendoring re-pins them. The
    // stylesheets carry no fetchable reference either (no `url(http`, no
    // `@import`); the one "@import" string in the bundle is its own
    // sanitizer's constant, not a rule.
    let plan = load(PLAN).expect("parses");
    let html = render::gantt_html(&plan, &schedule(&plan).expect("schedules"));
    assert!(!html.contains("fonts.gstatic.com"), "{html}");
    assert!(!html.contains("<script src="), "{html}");
    assert!(!html.contains("<link "), "{html}");
    assert!(!html.contains("url(http"), "{html}");
    assert!(!html.contains("url(//"), "{html}");
    assert_eq!(html.matches("<script").count(), 2, "{html}");
    assert_eq!(
        html.matches("http://").count(),
        2,
        "only the bundle's inert URL strings"
    );
    assert_eq!(html.matches("https://").count(), 9, "{html}");
    // The strip removes exactly the remote rules: the icon font's data-uri
    // @font-face survives.
    assert!(html.contains("@font-face{font-family:dhx-gantt-icons"), "{html}");
}

