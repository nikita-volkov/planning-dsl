#[test]
fn labels_are_escaped_in_both_renders() {
    // Names like these are refused at the door now (the slug rule), but the
    // renderers stay library functions over `Plan`: defensively, the escape
    // discipline holds for a plan that bypassed validation. Mermaid reads
    // the four entities; the HTML's data block carries the strings as JSON
    // with the parser-breaking characters written as \u escapes — nothing
    // raw survives into the markup.
    let yaml = "
unit: person-hours
deadline: 2026-12-18
roles:
  dev: implements
  r&d: researches
tasks:
  fix&ship: { role: dev }
  a<b: { role: dev }
  research: { role: r&d, estimate: 3 }
executors:
  anton: { roles: [dev, r&d] }
";
    let plan = load(yaml).expect("parses");
    let mmd = render::mermaid(&plan);
    assert!(mmd.contains("t0[\"fix&amp;ship\"]"), "{mmd}");
    assert!(mmd.contains("a&lt;b"), "{mmd}");
    let html = render::html(&plan, Direction::Tb, None);
    // Nothing raw survives into the data block (the bundles' inert code is
    // not ours to police): the block scope is where the plan's strings go.
    let start = start_of_block(&html);
    let end = start + html[start..].find("</script>").expect("the block closes");
    let block_text = &html[start..end];
    assert!(!block_text.contains("fix&ship"), "{block_text}");
    assert!(!block_text.contains("a<b"), "{block_text}");
    assert!(!block_text.contains("r&d"), "{block_text}");
    let block = data_block(&html);
    let research = block["tasks"]
        .as_array()
        .expect("tasks")
        .iter()
        .find(|t| t["name"] == "research")
        .expect("research in the block");
    assert_eq!(research["role"], "r&d");
    assert_eq!(research["estimate"], 3.0);
}

