/// The gantt's data block, extracted from the file and parsed: the golden
/// surface Rust owns — the structure the dhtmlx bundle draws and the
/// tooltip and quick_info templates read.
fn gantt_data(html: &str) -> Value {
    const OPEN: &str = "const DATA = ";
    let start = html.find(OPEN).expect("the data block is in the file") + OPEN.len();
    let end = start + html[start..].find(";\n").expect("the block ends");
    serde_json::from_str(&html[start..end]).expect("the data block parses as JSON")
}

#[test]
fn the_gantt_html_embeds_one_record_per_dated_task_and_marks_chain_and_statuses() {
    // The fixture: four tasks, design-architecture done and off the chart —
    // three task records under three project rows (the emulated executor
    // grouping), executors in first-appearance order. The chain
    // (plan-out-the-tasks → implement-services) carries critical:true;
    // implement-tests is blocked. end_date is the artifact's end + 1 day —
    // dhtmlx's end is exclusive — while the meta keeps the artifact's
    // inclusive end. The links are the edges whose both endpoints have a
    // bar; a done task has no dates, so no bar, so no link.
    let plan = load(PLAN).expect("parses");
    let artifact = schedule(&plan).expect("schedules");
    let html = render::gantt_html(&plan, &artifact);
    let data = gantt_data(&html);
    let rows = data["data"].as_array().expect("rows");
    assert_eq!(rows.len(), 6, "{html}"); // 3 project rows + 3 tasks
    let by_id = |id: &str| -> Value {
        rows.iter()
            .find(|t| t["id"] == id)
            .expect("row")
            .clone()
    };
    let headers: Vec<&str> = rows
        .iter()
        .filter(|t| t["meta"]["header"] == true)
        .map(|t| t["id"].as_str().expect("id"))
        .collect();
    assert_eq!(
        headers,
        ["grp-nikita", "grp-anton", "grp-review-agent"],
        "{html}"
    );
    assert!(rows.iter().all(|t| t["id"] != "design-architecture"), "{html}");
    let services = by_id("implement-services");
    assert_eq!(services["parent"], "grp-anton");
    assert_eq!(services["start_date"], "2026-11-12 00:00:00");
    assert_eq!(services["end_date"], "2026-11-19 00:00:00"); // end + 1
    assert_eq!(services["meta"]["executor"], "anton");
    assert_eq!(services["meta"]["start"], "2026-11-12");
    assert_eq!(services["meta"]["end"], "2026-11-18"); // the artifact's inclusive end
    assert_eq!(services["meta"]["active_days"], 5);
    assert_eq!(services["meta"]["status"], "todo");
    assert_eq!(services["meta"]["critical"], true);
    let plan_out = by_id("plan-out-the-tasks");
    assert_eq!(plan_out["parent"], "grp-nikita");
    assert_eq!(plan_out["meta"]["critical"], true);
    let tests = by_id("implement-tests");
    assert_eq!(tests["meta"]["status"], "blocked");
    assert_eq!(tests["meta"]["critical"], false);
    // The links: dependency first, the canonicalized edge set over dated
    // tasks; ids count from 1.
    let links = data["links"].as_array().expect("links");
    let pairs: Vec<(&str, &str)> = links
        .iter()
        .map(|l| {
            (
                l["source"].as_str().expect("source"),
                l["target"].as_str().expect("target"),
            )
        })
        .collect();
    assert_eq!(
        pairs,
        [
            ("plan-out-the-tasks", "implement-services"),
            ("plan-out-the-tasks", "implement-tests")
        ],
        "{html}"
    );
    let ids: Vec<i64> = links
        .iter()
        .map(|l| l["id"].as_i64().expect("id"))
        .collect();
    assert_eq!(ids, [1, 2], "{html}");
    // In-progress keeps its status and composes with the crit flag — this
    // one-task plan's chain is the task itself, and the row hangs under its
    // executor's project row.
    let yaml = "
unit: person-hours
start: 2026-11-02
roles:
  dev: implements
tasks:
  build: { role: dev, estimate: 8, status: in-progress }
executors:
  anton: { roles: [dev] }
";
    let plan = load(yaml).expect("parses");
    let html = render::gantt_html(&plan, &schedule(&plan).expect("schedules"));
    let rows = gantt_data(&html)["data"].as_array().expect("rows").clone();
    assert_eq!(rows.len(), 2, "{html}");
    assert_eq!(rows[0]["id"], "grp-anton");
    assert_eq!(rows[0]["meta"]["header"], true);
    assert_eq!(rows[1]["id"], "build");
    assert_eq!(rows[1]["meta"]["status"], "in-progress");
    assert_eq!(rows[1]["meta"]["critical"], true);
}

