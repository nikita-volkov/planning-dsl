// The CLI: the gantt is opt-in, and a scheduler refusal leaves no half-drawn
// set behind — everything is computed before anything is written.

fn tempdir(name: &str) -> std::path::PathBuf {
    let dir =
        std::env::temp_dir().join(format!("planning-dsl-render-{}-{name}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("tempdir");
    dir
}

fn render_cli(dir: &std::path::Path, yaml: &str, args: &[&str]) -> std::process::Output {
    let plan = dir.join("plan.yaml");
    std::fs::write(&plan, yaml).expect("fixture copy");
    let mut argv = vec![
        "render".to_string(),
        plan.to_str().expect("utf-8 tempdir").to_string(),
    ];
    argv.extend(args.iter().map(|s| s.to_string()));
    Command::new(binary())
        .args(&argv)
        .output()
        .expect("the binary runs")
}

/// The binary under test. `CARGO_BIN_EXE_planning_dsl` is the sanctioned
/// handle, but this cargo does not always expose it to test compilation, so
/// fall back to the sibling of the test's own target dir — the same
/// `<target>/<profile>/planning-dsl` the env var would name.
fn binary() -> std::path::PathBuf {
    let fallback = || {
        let exe = std::env::current_exe().expect("the test binary knows where it is");
        exe.ancestors()
            .nth(2)
            .expect("the profile dir above deps/")
            .join("planning-dsl")
    };
    std::env::var_os("CARGO_BIN_EXE_planning_dsl")
        .map(Into::into)
        .unwrap_or_else(fallback)
}

