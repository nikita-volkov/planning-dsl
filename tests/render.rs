#[test]
fn every_task_is_one_node_and_every_dependency_one_edge() {
    let plan = load(PLAN).expect("parses");
    let html = render::html(&plan, Direction::Tb, None);
    let block = data_block(&html);
    let names: Vec<&str> = block["tasks"]
        .as_array()
        .expect("tasks")
        .iter()
        .map(|t| t["name"].as_str().expect("name"))
        .collect();
    assert_eq!(
        names,
        [
            "design-architecture",
            "plan-out-the-tasks",
            "implement-services",
            "implement-tests"
        ]
    );
    let edges: Vec<(String, String, bool)> = block["edges"]
        .as_array()
        .expect("edges")
        .iter()
        .map(|e| {
            (
                e["from"].as_str().expect("from").to_string(),
                e["to"].as_str().expect("to").to_string(),
                e["crit"] == true,
            )
        })
        .collect();
    assert_eq!(edges.len(), 3, "{html}");
    assert!(edges.contains(&(
        "plan-out-the-tasks".to_string(),
        "implement-services".to_string(),
        false
    )));
    // The tracker state rides the record: design-architecture is done,
    // implement-tests is blocked; todo declares neither.
    let status_of = |name: &str| -> String {
        block["tasks"]
            .as_array()
            .expect("tasks")
            .iter()
            .find(|t| t["name"] == name)
            .expect("task")
            ["status"]
            .as_str()
            .unwrap_or("todo")
            .to_string()
    };
    assert_eq!(status_of("design-architecture"), "done");
    assert_eq!(status_of("implement-tests"), "blocked");
    assert_eq!(status_of("plan-out-the-tasks"), "todo");
}

